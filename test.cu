#include "config.h"
#include "helper.h"
#include <cuda_fp16.h> // FP16: __half, __half2float, __float2half
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>

// Kernel version : v0
// gpu compute tiled _v0 -- Kernel Config
// dim3 grid(NBC, NBC, TILES);
// dim3 block(N, 512);
// gpu_compute_tiled<<<grid, block>>>(g_data, g_output);
#define CHUNK 512				 // elements per channel held in shared memory
#define CHUNKS (BLOCK_SIZE * BLOCK_SIZE / CHUNK) // 16384 / 512 = 32

// Kernel config
// dim3 grid(NBC, NBC, CHUNKS);
// dim3 block(N, N);
// gpu_compute_tiled_v0<<<grid, block>>>(g_data, g_output);
__global__ void gpu_compute_tiled_v3(const __half *data, double (*output)[N][N])
{
	// block position
	int row = blockIdx.x;
	int col = blockIdx.y;

	__shared__ __half temp1[16][CHUNK + 1]; // 16 * 512 * 2 bytes = 16 KB

	int origin = MATRIX_SIZE * BLOCK_SIZE * row + col * BLOCK_SIZE;

	int i = threadIdx.x; // range from 0..16
	int j = threadIdx.y; // range from 0..16

	// fill up [16][512] chunk out of [16][128*128]
	// the 16 threads along y share the work, each loads 512/16 = 32 elements
	for (int t = j; t < CHUNK; t += 16) {
		int e = blockIdx.z * CHUNK + t;
		temp1[i][t] = data[i * MATRIX_SIZE * MATRIX_SIZE + origin +
				   (e / BLOCK_SIZE) * MATRIX_SIZE + (e % BLOCK_SIZE)];
	}

	__syncthreads();
	// multiply [16][512] with [512][16] get [16][16]

	double sum = 0;
	for (int k = 0; k < CHUNK; ++k)
		sum += (double)(__half2float(temp1[i][k]) * __half2float(temp1[j][k]));

	// add the [16][16] if same block (by block id)
	int blk = row * NBC + col; // block id
	atomicAdd(&output[blk][i][j], sum);
}
int main()
{
	int *h_data;	// FP16: int host copy kept for read_data / print_input_data
	__half *h_half; // FP16: converted host copy
	__half *g_data; // FP16: device input is __half
	const size_t n_elem = (size_t)N * MATRIX_SIZE * MATRIX_SIZE;

	h_data = (int *)malloc(sizeof(int) * n_elem);
	h_half = (__half *)malloc(sizeof(__half) * n_elem); // FP16
	cudaMalloc(&g_data, sizeof(__half) * n_elem);	    // FP16: was sizeof(int)

	read_data(h_data);

	// FP16: convert int input -> half on the host (values 0..9 are exact in fp16)
	for (size_t i = 0; i < n_elem; ++i)
		h_half[i] = __float2half((float)h_data[i]);

	cudaMemcpy(g_data, h_half, sizeof(__half) * n_elem, cudaMemcpyHostToDevice); // FP16

	// print input data to match with the cpu refernce generated by main
	print_input_data(h_data);

	double (*h_output)[N][N], (*g_output)[N][N];
	h_output = (double (*)[N][N])malloc(sizeof(double) * NBLK * N * N);
	cudaMalloc(&g_output, sizeof(double) * NBLK * N * N);

	cudaMemset(g_output, 0, sizeof(double) * NBLK * N * N);

	//-   Kernel config v0------
	// // gpu compute tiled _v0
	// dim3 grid(NBC, NBC, TILES);
	// dim3 block(N, TILE_SIZE);
	// gpu_compute_tiled_v0<<<grid, block>>>(g_data, g_output);

	// // kernel config v1 ------------ without Atomic ADD
	// dim3 grid(NBC, NBC);
	// dim3 block(N, TILE_SIZE);
	// gpu_compute_tiled_v1<<<grid, block>>>(g_data, g_output);
	//
	// // kernel config v2 --------
	// dim3 grid(NBC, NBC, SPLIT); // 8 x 8 x 16 = 1024 CTAs
	// dim3 block(N, TILE_SIZE);   // 16 x 16, same as v1
	// gpu_compute_tiled_v2<<<grid, block>>>(g_data, g_output);
	dim3 grid(NBC, NBC, CHUNKS); // 8 x 8 x 32 = 2048 CTAs
	dim3 block(N, N);	     // 16 x 16 = 256 threads
	gpu_compute_tiled_v3<<<grid, block>>>(g_data, g_output);

	cudaMemcpy(h_output, g_output, sizeof(double) * NBLK * N * N, cudaMemcpyDeviceToHost);

	// print outputs : should match with the output generated by  main
	for (int b = 0; b < NBLK; ++b) {
		printf("block %3d", b);
		for (int i = 0; i < N; ++i) {
			for (int j = 0; j < N; ++j)
				printf("  %5.0f", h_output[b][i][j]);
		}
		printf("\n");
	}

	// deallocate memmory
	free(h_data);
	free(h_half); // FP16
	cudaFree(g_data);
	cudaFree(g_output);
}
